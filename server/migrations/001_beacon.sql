CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE people (
    id TEXT PRIMARY KEY,
    name TEXT,
    notes TEXT DEFAULT '',
    is_watch INTEGER DEFAULT 0,
    watch_label TEXT DEFAULT '',
    crop TEXT,
    created_at DOUBLE PRECISION,
    last_seen DOUBLE PRECISION,
    met INTEGER DEFAULT 0,
    met_at DOUBLE PRECISION,
    met_lat DOUBLE PRECISION,
    met_lng DOUBLE PRECISION,
    category TEXT
);

-- Explicit rowid preserves the existing API's training-photo IDs and undo data.
CREATE TABLE embeddings (
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id TEXT NOT NULL REFERENCES people(id) ON DELETE CASCADE,
    vec vector(512) NOT NULL,
    created_at DOUBLE PRECISION,
    crop TEXT,
    quality DOUBLE PRECISION DEFAULT 0,
    source TEXT DEFAULT 'auto'
);

CREATE TABLE nodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    x DOUBLE PRECISION,
    y DOUBLE PRECISION,
    keyframe TEXT,
    qr TEXT,
    created_at DOUBLE PRECISION,
    visits INTEGER DEFAULT 1,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION
);

CREATE TABLE sightings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id TEXT NOT NULL REFERENCES people(id) ON DELETE CASCADE,
    ts DOUBLE PRECISION,
    node_id BIGINT REFERENCES nodes(id) ON DELETE SET NULL,
    x DOUBLE PRECISION,
    y DOUBLE PRECISION,
    sim DOUBLE PRECISION,
    crop TEXT,
    frame TEXT,
    box TEXT,
    quality DOUBLE PRECISION DEFAULT 0,
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION
);

CREATE TABLE categories (
    name TEXT PRIMARY KEY,
    sort INTEGER DEFAULT 0,
    created_at DOUBLE PRECISION
);

CREATE TABLE edges (
    a BIGINT REFERENCES nodes(id) ON DELETE CASCADE,
    b BIGINT REFERENCES nodes(id) ON DELETE CASCADE,
    dist DOUBLE PRECISION,
    crowd DOUBLE PRECISION DEFAULT 0,
    blocked INTEGER DEFAULT 0,
    PRIMARY KEY (a, b)
);

-- Bind the shared gallery to its embedding model, including across computers.
CREATE TABLE beacon_metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE INDEX embeddings_person_idx ON embeddings(person_id);
CREATE INDEX sightings_person_ts_idx ON sightings(person_id, ts DESC);
CREATE INDEX sightings_ts_idx ON sightings(ts DESC);
CREATE INDEX people_last_seen_idx ON people(last_seen DESC);
